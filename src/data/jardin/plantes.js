const CLES = ['taille', 'arrosage', 'soleil', 'plantation', 'multi', 'rust']

function P(id, nom, latin, categorie, emoji, resume, conseils, actions = []) {
  return {
    id,
    nom,
    latin,
    categorie,
    emoji,
    resume,
    conseils: Object.fromEntries(CLES.map((c, i) => [c, (conseils[i] || '').split('|').filter(Boolean)])),
    actions: actions.map(([type, mois, texte], i) => ({ id: `${id}-${i}`, type, mois, texte })),
  }
}

